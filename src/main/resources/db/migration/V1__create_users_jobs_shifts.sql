CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE jobs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users (id),
    employer_name       VARCHAR(150)  NOT NULL,
    weekday_rate        NUMERIC(8, 2) NOT NULL CHECK (weekday_rate > 0),
    saturday_rate       NUMERIC(8, 2) NOT NULL CHECK (saturday_rate > 0),
    sunday_rate         NUMERIC(8, 2) NOT NULL CHECK (sunday_rate > 0),
    public_holiday_rate NUMERIC(8, 2) NOT NULL CHECK (public_holiday_rate > 0),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE shifts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id        BIGINT       NOT NULL REFERENCES jobs (id),
    start_time    TIMESTAMPTZ  NOT NULL,
    end_time      TIMESTAMPTZ  NOT NULL,
    break_minutes INT          NOT NULL DEFAULT 0 CHECK (break_minutes >= 0),
    note          VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (end_time > start_time)
);

CREATE INDEX idx_jobs_user_id ON jobs (user_id);
CREATE INDEX idx_shifts_job_id_start ON shifts (job_id, start_time);
